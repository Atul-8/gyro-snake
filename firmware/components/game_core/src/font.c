const uint8_t *font5x7_glyph(char c)
{
    unsigned v = (unsigned char)c;

    if (v >= (unsigned)'a' && v <= (unsigned)'z') {
        v -= ('a' - 'A');
    }
    if (v < (unsigned)FONT_FIRST || v > (unsigned)FONT_LAST) {
        v = (unsigned)' ';
    }
    return k_font5x7[v - (unsigned)FONT_FIRST];
}